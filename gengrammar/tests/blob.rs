use gengrammar::blob::{Blob, LangInfo, check_language, write_blob};
use gengrammar::lock::LockEntry;
use gengrammar::parse::{Grammar, parse_grammar};
use gengrammar::rust::{header, mod_rs};

const LANG: &str = include_str!("../../testdata/gengrammar/mini_lang.c");

fn mini() -> (Grammar, LangInfo, Blob) {
    let mut g = parse_grammar(LANG).unwrap();
    let info = check_language(&mut g).unwrap();
    let blob = write_blob(&g, &info);
    (g, info, blob)
}

fn sect<'a>(b: &'a Blob, name: &str) -> &'a [u8] {
    let s = b
        .sections
        .iter()
        .find(|s| s.name == name)
        .unwrap_or_else(|| panic!("no section {name}"));
    &b.bytes[s.offset..]
}

#[test]
fn small_parse_table_bytes() {
    let (_, _, b) = mini();
    assert_eq!(
        &sect(&b, "ts_small_parse_table")[..16],
        [1, 0, 3, 0, 1, 0, 2, 0, 0, 0, 0, 0, 0, 0, 2, 0]
    );
}

#[test]
fn lex_mode_rows() {
    let (_, _, b) = mini();
    let m = sect(&b, "ts_lex_modes");
    assert_eq!(&m[6..12], [5, 0, 2, 0, 0, 0]);
    assert_eq!(&m[18..24], [0xff, 0xff, 0, 0, 0, 0]);
}

#[test]
fn parse_action_slots() {
    let (_, _, b) = mini();
    let a = sect(&b, "ts_parse_actions");
    // slot 1: header, count 2, reusable
    assert_eq!(&a[8..16], [2, 1, 0, 0, 0, 0, 0, 0]);
    // slot 2: REDUCE(sym_b, 2, -1, 7)
    assert_eq!(&a[16..24], [0x01, 0x02, 0x02, 0x00, 0xff, 0xff, 0x07, 0x00]);
    // slot 3: SHIFT_REPEAT(9)
    assert_eq!(&a[24..32], [0, 0, 9, 0, 2, 0, 0, 0]);
    // slot 5: SHIFT_EXTRA()
    assert_eq!(&a[40..48], [0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]);
}

#[test]
fn other_element_encodings() {
    let (_, _, b) = mini();
    // visible/named/supertype in bits 0, 1, 2
    assert_eq!(&sect(&b, "ts_symbol_metadata")[..3], [2, 3, 5]);
    // TSFieldMapSlice: index, length
    assert_eq!(
        &sect(&b, "ts_field_map_slices")[..8],
        [0, 0, 0, 0, 0, 0, 1, 0]
    );
    // TSFieldMapEntry: field_id u16, child_index u8, inherited u8
    assert_eq!(&sect(&b, "ts_field_map_entries")[..4], [1, 0, 0, 0]);
    // bool, one byte each
    assert_eq!(&sect(&b, "ts_external_scanner_states")[..3], [0, 1, 1]);
    // uint32_t
    assert_eq!(
        &sect(&b, "ts_small_parse_table_map")[..8],
        [0, 0, 0, 0, 7, 0, 0, 0]
    );
}

#[test]
fn sections_are_in_order_padded_and_8_aligned() {
    let (g, info, b) = mini();
    let want: Vec<&str> = g
        .order
        .iter()
        .map(String::as_str)
        .filter(|n| info.used.iter().any(|u| u == n))
        .filter(|n| !matches!(g.tables[*n].ctype.as_str(), "char*" | "TSCharacterRange"))
        .collect();
    let got: Vec<&str> = b.sections.iter().map(|s| s.name.as_str()).collect();
    assert_eq!(got, want);
    assert!(!got.contains(&"ts_symbol_names"));
    assert!(!got.contains(&"set_1"));
    for s in &b.sections {
        assert_eq!(s.offset % 8, 0, "{}", s.name);
    }
    for w in b.sections.windows(2) {
        assert!(w[1].offset > w[0].offset);
        assert!(w[1].offset - w[0].offset >= 8);
    }
    assert_eq!(b.bytes.len() % 8, 0);
    let by = |n: &str| {
        let s = b.sections.iter().find(|s| s.name == n).unwrap();
        (s.offset, s.count)
    };
    assert_eq!(by("ts_small_parse_table"), (0, 8));
    assert_eq!(by("ts_small_parse_table_map"), (16, 2));
    assert_eq!(by("ts_lex_modes"), (24, 4));
    assert_eq!(by("ts_parse_actions"), (48, 6));
    assert_eq!(by("ts_parse_table"), (128, 6));
    assert_eq!(b.bytes.len(), 184);
}

#[test]
fn scalar_table_keeps_its_trailing_zero_run() {
    // Go's scalarTable case `11: 0`: the table is 12 elements long.
    let g = parse_grammar("static const uint16_t ts_x[] = { [1] = 5, [11] = 0, };").unwrap();
    let info = LangInfo {
        used: vec!["ts_x".into()],
        ..LangInfo::default()
    };
    let b = write_blob(&g, &info);
    let mut want = vec![0u8; 24];
    want[2] = 5;
    assert_eq!(b.bytes, want);
    assert_eq!((b.sections[0].offset, b.sections[0].count), (0, 12));
}

#[test]
fn mod_rs_text() {
    let (g, info, b) = mini();
    let l = LockEntry {
        pkg: "mini".into(),
        module: "example.com/mini".into(),
        version: "v1.2.3".into(),
        dir: "src".into(),
        sum: String::new(),
    };
    let hdr = header(&l, "abc123");
    assert_eq!(
        hdr,
        "// @generated by gengrammar from example.com/mini@v1.2.3. DO NOT EDIT.\n\
         // Source: src/parser.c, sha256 abc123.\n"
    );
    let t = mod_rs(&hdr, &g, &info, &b, false);
    assert!(t.starts_with(&hdr), "{t}");
    for line in [
        "#![allow(non_upper_case_globals)]",
        "pub const sym_a: u16 = 1;",
        "pub const sym_b: u16 = 2;",
        "pub const ts_external_token_x: u16 = 0;",
        "pub const COUNTS: Counts = Counts {",
        "    abi_version: 14,",
        "    symbol_count: 3,",
        "    keyword_capture_token: 0,",
        "pub const TS_SMALL_PARSE_TABLE: (usize, usize) = (0, 8);",
        "pub const TS_PARSE_ACTIONS: (usize, usize) = (48, 6);",
        "pub static SYMBOL_NAMES: &[&str] = &[\"end\", \"\\\"a?\", \"\"];",
        "pub static FIELD_NAMES: &[&str] = &[\"\", \"f\"];",
        "static TABLES: &[u8] = include_bytes!(\"tables.bin\");",
    ] {
        assert!(t.lines().any(|l| l == line), "missing {line:?} in\n{t}");
    }
    // char* and TSCharacterRange tables are not in the blob
    assert!(!t.contains("TS_SYMBOL_NAMES"));
    assert!(!t.contains("SET_1"));
}
